def image_cards(title, path, cards, lead=None, notes=None, img_h=3.15, card_size=13.5):
    """위: 전체 폭 그림 / 아래: 가로 카드 한 줄."""
    s = d.blank(title, notes)
    y = Y0
    if lead:
        d.lead(s, lead)
        y += 0.65
    d._image_fit(s, path, X0, y + 0.05, W, img_h)
    cy = y + img_h + 0.2
    n = len(cards)
    gap = 0.25
    cw = (W - gap * (n - 1)) / n
    ch = Y1 - cy
    for i, c in enumerate(cards):
        cx = X0 + i * (cw + gap)
        acc = c.get("accent")
        d.box(s, cx, cy, cw, ch, fill=ACCENT_BG if acc else MINT)
        d.text(s, cx + 0.15, cy + 0.08, cw - 0.3, 0.45, c["head"], size=15.5, bold=True,
               color=ACCENT if acc else TEAL, anchor="m", min_size=11)
        d.text(s, cx + 0.15, cy + 0.55, cw - 0.3, ch - 0.62, c["body"], size=card_size, min_size=9,
               para_gap=0.25, bullets=isinstance(c["body"], list) and len(c["body"]) > 1)
    return s


