# deckkit.py 자체는 수정하지 않고, 이 빌드 스크립트 안에서만 parse_inline을 감싼다.
_SUBSUP = re.compile(r"([^\s(),\[\]:;]*[₀-₉⁰-⁹⁻ᵀ][^\s(),\[\]:;]*)")
_orig_parse_inline = deckkit.parse_inline


def _parse_inline_subsup(text):
    out = []
    for seg, st in _orig_parse_inline(text):
        if st.get("mono") or not _SUBSUP.search(seg):
            out.append((seg, st))
            continue
        for k, piece in enumerate(_SUBSUP.split(seg)):
            if piece:
                out.append((piece, dict(st, mono=True) if k % 2 else st))
    return out


deckkit.parse_inline = _parse_inline_subsup

